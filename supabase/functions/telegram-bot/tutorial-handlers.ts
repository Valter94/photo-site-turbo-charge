
import { SupabaseClient } from 'https://esm.sh/@supabase/supabase-js@2'

export const createTutorialHandlers = (supabase: SupabaseClient, telegramAPI: any) => {
  const sendTutorialVideo = async (chatId: number) => {
    const tutorialText = `
🎥 <b>Полная инструкция по управлению вашим сайтом фотографа</b>

🎯 <b>Быстрый старт - основные команды:</b>
• /start - главное меню с кнопками
• /help - показать эту инструкцию
• /stats - статистика сайта

📸 <b>1. Управление портфолио через бот</b>
• Выберите "📸 Добавить в портфолио"
• Отправьте фото (можно несколько сразу)
• Введите название
• Выберите категорию кнопкой
• Добавьте описание

✨ <b>2. Обработка фотографий в боте</b>
• Выберите "🎨 Обработать фото"
• Загрузите до 10 фото одновременно
• Выберите стиль обработки
• Можете приложить эталонное фото для стиля
• Получите обработанные фото
• Добавьте лучшие в портфолио

📍 <b>3. Добавление локаций</b>
• Выберите "📍 Добавить локацию"
• Отправьте фото места
• Введите название и описание
• Локация появится на сайте

💰 <b>4. Управление ценами</b>
• "💰 Управление ценами" → просмотр тарифов
• "✏️ Редактировать цены" → изменение тарифов
• Изменения сразу отражаются на сайте

📊 <b>5. Статистика и аналитика</b>
• "📊 Статистика" - посещения, заявки, популярные фото
• Данные обновляются в реальном времени
• Экспорт данных для анализа

🔧 <b>6. Административная панель сайта</b>
• Перейдите на ваш-сайт.com/admin
• Полное управление всем контентом
• Настройка SEO и аналитики
• Управление отзывами и заявками

⭐ <b>Возможности вашего сайта:</b>
✅ Адаптивная галерея портфолио
✅ Система онлайн-бронирования
✅ База локаций для съемки
✅ Управление ценами и услугами
✅ Отзывы клиентов
✅ CRM для управления заявками
✅ SEO оптимизация
✅ Telegram бот для управления
✅ Обработка фото с ИИ

🎨 <b>Новые функции обработки:</b>
• Автоматическая коррекция цвета
• Ретушь кожи и глаз
• Художественные фильтры
• Обработка по эталону
• Пакетная обработка до 10 фото

🚀 <b>Быстрые действия:</b>
• Для добавления фото: /start → "📸 Добавить в портфолио"
• Для обработки: /start → "🎨 Обработать фото"
• Для статистики: /stats

💡 <b>Совет:</b> Это сообщение автоматически закреплено для быстрого доступа!

❓ <b>Нужна помощь?</b> Отправьте /help в любое время для повторного показа инструкций.
    `

    try {
      const result = await telegramAPI.sendMessage(chatId, tutorialText, {
        inline_keyboard: [
          [
            { text: '📸 Добавить фото', callback_data: 'add_portfolio' },
            { text: '🎨 Обработать фото', callback_data: 'process_photos' }
          ],
          [
            { text: '📍 Добавить локацию', callback_data: 'add_location' },
            { text: '💰 Управление ценами', callback_data: 'manage_pricing' }
          ],
          [
            { text: '📊 Статистика', callback_data: 'stats' },
            { text: '🏠 Главное меню', callback_data: 'main_menu' }
          ]
        ]
      })
      
      // Автоматически закрепляем наши инструкции
      if (result.ok) {
        try {
          await fetch(`https://api.telegram.org/bot${Deno.env.get('TELEGRAM_BOT_TOKEN')}/pinChatMessage`, {
            method: 'POST',
            headers: { 'Content-Type': 'application/json' },
            body: JSON.stringify({
              chat_id: chatId,
              message_id: result.result.message_id,
              disable_notification: true
            })
          })
          console.log('📌 Инструкции по управлению сайтом закреплены')
        } catch (pinError) {
          console.warn('⚠️ Не удалось закрепить инструкции:', pinError)
        }
      }
      
      return true
    } catch (error) {
      console.error('❌ Ошибка отправки инструкций:', error)
      return false
    }
  }

  return { sendTutorialVideo }
}
